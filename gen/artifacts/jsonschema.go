package artifacts

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"

	"github.com/epistemer/cfgx/internal/ir"
)

// jsonSchemaDraft is the $schema URI of the produced document.
const jsonSchemaDraft = "http://json-schema.org/draft-07/schema#"

// durationPattern matches Go duration strings, including compound ones such
// as "1h30m" and the bare "0".
const durationPattern = `^-?(\d+(\.\d+)?(ns|us|µs|ms|s|m|h))+$|^0$`

// semverPattern matches semantic versions with an optional "v" prefix.
const semverPattern = `^v?\d+\.\d+\.\d+`

// JSONSchema generates a config.schema.json (JSON Schema draft-07) from schema.
//
// Objects nest "properties" and "required"; computed entries are omitted;
// sensitive entries are "writeOnly" and never carry a default. Keys are sorted,
// so output is deterministic.
func JSONSchema(schema *ir.SchemaIR) ([]byte, error) {
	if err := checkSchema("JSONSchema", schema); err != nil {
		return nil, err
	}
	root := map[string]any{
		"$schema":  jsonSchemaDraft,
		"$comment": "Generated by cfgx. Do not edit manually.",
		"type":     "object",
	}
	if err := addProperties(root, schema.Entries); err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(root); err != nil {
		return nil, fmt.Errorf("artifacts: JSONSchema: %w", err)
	}
	return buf.Bytes(), nil
}

// addProperties sets "properties" and "required" on obj from entries.
func addProperties(obj map[string]any, entries []ir.EntryIR) error {
	props := map[string]any{}
	var required []string
	for i := range entries {
		e := &entries[i]
		if e.Type == ir.TypeComputed {
			continue
		}
		p, err := propertySchema(e)
		if err != nil {
			return err
		}
		props[e.ID] = p
		if e.Required {
			required = append(required, e.ID)
		}
	}
	obj["properties"] = props
	if len(required) > 0 {
		sort.Strings(required)
		obj["required"] = required
	}
	return nil
}

// propertySchema builds the schema of one entry.
func propertySchema(e *ir.EntryIR) (map[string]any, error) {
	p := typeSchema(e)
	desc := oneLine(e.Description)
	if e.Deprecated != "" {
		p["deprecated"] = true
		msg := "DEPRECATED: " + oneLine(e.Deprecated)
		if desc == "" {
			desc = msg
		} else {
			desc += " (" + msg + ")"
		}
	}
	if desc != "" {
		p["description"] = desc
	}
	if hasDefault(e) {
		p["default"] = e.Default
	}
	if e.Sensitive {
		p["writeOnly"] = true
	}
	if e.Env != "" {
		p["x-env"] = e.Env
	}
	if e.FlagLong != "" {
		p["x-flag"] = e.FlagLong
	}
	if e.Type == ir.TypeObject {
		if err := addProperties(p, e.Properties); err != nil {
			return nil, err
		}
	}
	return p, nil
}

// typeSchema returns the type keywords and validator keywords of e (used for
// both properties and list elements).
func typeSchema(e *ir.EntryIR) map[string]any {
	p := map[string]any{}
	switch e.Type {
	case ir.TypeString:
		p["type"] = "string"
	case ir.TypeDuration:
		p["type"] = "string"
		p["pattern"] = durationPattern
	case ir.TypeInt:
		p["type"] = "integer"
	case ir.TypeFloat64:
		p["type"] = "number"
	case ir.TypeBool:
		p["type"] = "boolean"
	case ir.TypeList:
		p["type"] = "array"
		if e.ElementType != nil {
			p["items"] = typeSchema(e.ElementType)
		}
	case ir.TypeObject:
		p["type"] = "object"
	}
	for _, v := range e.BuiltinValidators {
		applyValidator(p, v)
	}
	return p
}

// applyValidator adds the JSON Schema keywords for a built-in validator.
func applyValidator(p map[string]any, v ir.ValidatorIR) {
	switch v.Name {
	case "email":
		p["format"] = "email"
	case "url":
		p["format"] = "uri"
	case "port":
		p["minimum"] = 1
		p["maximum"] = 65535
	case "port_range", "range":
		if lo, ok := v.Params["min"]; ok {
			p["minimum"] = lo
		}
		if hi, ok := v.Params["max"]; ok {
			p["maximum"] = hi
		}
	case "base64":
		p["contentEncoding"] = "base64"
	case "regex":
		if pat, ok := v.Params["pattern"]; ok {
			p["pattern"] = pat
		}
	case "duration":
		p["pattern"] = durationPattern
	case "semver":
		p["pattern"] = semverPattern
	case "enum":
		if vals, ok := v.Params["values"]; ok {
			p["enum"] = vals
		}
	}
}
