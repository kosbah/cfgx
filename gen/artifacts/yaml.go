package artifacts

import (
	"bytes"
	"sort"
	"strconv"
	"strings"

	"github.com/epistemer/cfgx/internal/ir"
)

// yamlIndent is the number of spaces per nesting level.
const yamlIndent = 2

// YAMLExample generates a config.example.yaml file from schema.
//
// Top-level entries are grouped into sections by tag (first-appearance order,
// "Other" last) and sorted by ID; object properties are nested as block
// mappings, also sorted by ID. Computed entries appear only as a comment and
// sensitive values are always empty.
func YAMLExample(schema *ir.SchemaIR) ([]byte, error) {
	if err := checkSchema("YAMLExample", schema); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("# cfgx example configuration\n")
	b.WriteString("# Generated by cfgx. Update with your values.\n")

	type group struct {
		title   string
		entries []*ir.EntryIR
	}
	var groups []*group
	index := map[string]*group{}
	var other group
	for i := range schema.Entries {
		e := &schema.Entries[i]
		if len(e.Tags) == 0 {
			other.entries = append(other.entries, e)
			continue
		}
		g, ok := index[e.Tags[0]]
		if !ok {
			g = &group{title: tagTitle(e.Tags[0])}
			index[e.Tags[0]] = g
			groups = append(groups, g)
		}
		g.entries = append(g.entries, e)
	}
	if len(other.entries) > 0 {
		other.title = otherSection
		groups = append(groups, &other)
	}
	for _, g := range groups {
		b.WriteString("\n" + rule("# ", g.title, ruleWidth) + "\n")
		for i, e := range sortedByID(g.entries) {
			if i > 0 {
				b.WriteByte('\n')
			}
			writeYAMLEntry(&b, e, 0)
		}
	}
	return b.Bytes(), nil
}

// sortedByID returns a copy of entries sorted by ID.
func sortedByID(entries []*ir.EntryIR) []*ir.EntryIR {
	out := append([]*ir.EntryIR(nil), entries...)
	sort.SliceStable(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

func writeYAMLEntry(b *bytes.Buffer, e *ir.EntryIR, depth int) {
	pad := strings.Repeat(" ", depth*yamlIndent)
	comment := func(s string) { b.WriteString(pad + "# " + s + "\n") }

	desc := oneLine(e.Description)
	if e.Required && e.Type != ir.TypeComputed {
		if desc == "" {
			desc = "(required)"
		} else {
			desc += " (required)"
		}
	}
	if desc != "" {
		comment(desc)
	}
	if e.Deprecated != "" {
		comment("DEPRECATED: " + oneLine(e.Deprecated))
	}
	if e.Type == ir.TypeComputed {
		comment(e.ID + " is computed; do not set manually")
		return
	}
	if e.Sensitive {
		comment("sensitive — do not commit this value")
	}
	key := yamlKey(e.ID)

	switch e.Type {
	case ir.TypeObject:
		b.WriteString(pad + key + ":\n")
		props := make([]*ir.EntryIR, len(e.Properties))
		for i := range e.Properties {
			props[i] = &e.Properties[i]
		}
		for _, p := range sortedByID(props) {
			writeYAMLEntry(b, p, depth+1)
		}
	case ir.TypeList:
		var items []any
		if hasDefault(e) {
			items = listItems(e.Default)
		}
		if len(items) == 0 {
			b.WriteString(pad + key + ": []\n")
			return
		}
		b.WriteString(pad + key + ":\n")
		itemPad := strings.Repeat(" ", (depth+1)*yamlIndent)
		for _, it := range items {
			b.WriteString(itemPad + "- " + yamlValue(it) + "\n")
		}
	default:
		v := e.Default
		if !hasDefault(e) {
			v = nil
		}
		b.WriteString(pad + key + ": " + yamlScalar(e.Type, v) + "\n")
	}
}

// yamlScalar renders a scalar entry value of type t; nil yields the type's
// zero value.
func yamlScalar(t ir.EntryType, v any) string {
	if v == nil {
		switch t {
		case ir.TypeInt:
			return "0"
		case ir.TypeFloat64:
			return "0.0"
		case ir.TypeBool:
			return "false"
		}
		return `""`
	}
	if t == ir.TypeFloat64 {
		if f, ok := toFloat(v); ok {
			s := formatFloat(f)
			if !strings.ContainsAny(s, ".eEIN") {
				s += ".0"
			}
			return s
		}
	}
	return yamlValue(v)
}

func toFloat(v any) (float64, bool) {
	switch x := v.(type) {
	case float64:
		return x, true
	case int:
		return float64(x), true
	case int64:
		return float64(x), true
	}
	return 0, false
}

// yamlValue renders an arbitrary scalar literal: strings go through
// yamlString, everything else as plain text.
func yamlValue(v any) string {
	if s, ok := v.(string); ok {
		return yamlString(s)
	}
	return scalarText(v)
}

// yamlKey renders a mapping key, quoting it when YAML would misread it.
func yamlKey(k string) string { return yamlString(k) }

// yamlReserved are plain scalars YAML (1.1 or 1.2) resolves to non-strings.
var yamlReserved = map[string]bool{
	"true": true, "false": true, "yes": true, "no": true, "on": true, "off": true,
	"y": true, "n": true, "null": true, "~": true,
	".inf": true, "-.inf": true, "+.inf": true, ".nan": true,
}

// yamlString renders s as a plain scalar unless YAML would misread it, in
// which case it is double-quoted.
func yamlString(s string) string {
	if yamlNeedsQuote(s) {
		return strconv.Quote(s)
	}
	return s
}

func yamlNeedsQuote(s string) bool {
	if s == "" || yamlReserved[strings.ToLower(s)] {
		return true
	}
	if strings.TrimSpace(s) != s {
		return true
	}
	if strings.ContainsAny(s[:1], "-?:#&*!|>'\"%@`,[]{}") {
		return true
	}
	if strings.Contains(s, ": ") || strings.Contains(s, " #") || strings.HasSuffix(s, ":") {
		return true
	}
	for _, r := range s {
		if r < 0x20 || r == 0x7f {
			return true
		}
	}
	return looksNumeric(s)
}

// looksNumeric reports whether a plain scalar would resolve to a number.
func looksNumeric(s string) bool {
	t := strings.ReplaceAll(s, "_", "")
	if _, err := strconv.ParseFloat(t, 64); err == nil {
		return true
	}
	if _, err := strconv.ParseInt(t, 0, 64); err == nil {
		return true
	}
	return false
}
