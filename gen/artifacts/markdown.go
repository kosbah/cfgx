package artifacts

import (
	"bytes"
	"strings"

	"github.com/example/cfgx/internal/ir"
)

// none marks an empty table cell.
const none = "—"

// Markdown generates a config.md reference document from schema.
//
// Every non-object entry gets a row in its tag's section (first-appearance
// order, "Other" last, sorted by key). Deprecated entries are listed
// separately at the bottom, followed by notes for schema-level constraints.
func Markdown(schema *ir.SchemaIR) ([]byte, error) {
	if err := checkSchema("Markdown", schema); err != nil {
		return nil, err
	}
	secs, deprecated := sections(flatten(schema.Entries), true)

	var b bytes.Buffer
	b.WriteString("# Configuration Reference\n\nGenerated by cfgx. Do not edit manually.\n\n---\n")
	for _, sec := range secs {
		b.WriteString("\n## " + sec.Title + "\n\n")
		b.WriteString("| Name | Env | Flag | Type | Default | Required | Description |\n")
		b.WriteString("|------|-----|------|------|---------|----------|-------------|\n")
		for _, l := range sec.Leaves {
			e := l.Entry
			required := "No"
			if e.Required {
				required = "**Yes**"
			}
			cells := []string{code(l.Key), optCode(e.Env), mdFlags(e), mdType(e), mdDefault(e), required, mdDescription(e)}
			b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
		}
	}
	if len(deprecated) > 0 {
		b.WriteString("\n## Deprecated\n\n")
		b.WriteString("| Name | Env | Type | Deprecation message |\n")
		b.WriteString("|------|-----|------|---------------------|\n")
		for _, l := range deprecated {
			cells := []string{"~~" + code(l.Key) + "~~", optCode(l.Entry.Env), mdType(l.Entry), mdText(l.Deprecated)}
			b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
		}
	}
	var notes []string
	for _, c := range schema.Constraints {
		if c.Type != ir.ConstraintMutuallyExclusive || len(c.EntryIDs) == 0 {
			continue
		}
		ids := make([]string, len(c.EntryIDs))
		for i, id := range c.EntryIDs {
			ids[i] = code(id)
		}
		notes = append(notes, "> **Note:** "+joinAnd(ids)+" are mutually exclusive; set at most one of them.\n")
	}
	if len(notes) > 0 {
		b.WriteString("\n## Constraints\n\n")
		b.WriteString(strings.Join(notes, ">\n"))
	}
	return b.Bytes(), nil
}

// joinAnd joins items as "a", "a and b" or "a, b and c".
func joinAnd(items []string) string {
	if len(items) <= 1 {
		return strings.Join(items, "")
	}
	return strings.Join(items[:len(items)-1], ", ") + " and " + items[len(items)-1]
}

func mdFlags(e *ir.EntryIR) string {
	var flags []string
	if e.FlagLong != "" {
		flags = append(flags, code(e.FlagLong))
	}
	if e.FlagShort != "" {
		flags = append(flags, code(e.FlagShort))
	}
	if len(flags) == 0 {
		return none
	}
	return strings.Join(flags, ", ")
}

func mdType(e *ir.EntryIR) string {
	t := typeName(e)
	if e.Sensitive {
		t += " 🔒"
	}
	return t
}

func mdDefault(e *ir.EntryIR) string {
	if !hasDefault(e) {
		return none
	}
	if e.Type == ir.TypeList {
		items := listItems(e.Default)
		parts := make([]string, len(items))
		for i, it := range items {
			parts[i] = scalarText(it)
		}
		return code("[" + strings.Join(parts, ", ") + "]")
	}
	if s := scalarText(e.Default); s != "" {
		return code(s)
	}
	return code(`""`)
}

func mdDescription(e *ir.EntryIR) string {
	d := oneLine(e.Description)
	if e.Type == ir.TypeComputed {
		if d == "" {
			d = "derived from siblings"
		} else {
			d += " (derived from siblings)"
		}
	}
	if e.IsLive {
		if d == "" {
			d = "(🔄 hot-reload)"
		} else {
			d += " (🔄 hot-reload)"
		}
	}
	return mdText(d)
}

// mdText makes s safe for a table cell: one line, "|" escaped.
func mdText(s string) string {
	return strings.ReplaceAll(oneLine(s), "|", `\|`)
}

// optCode renders s as inline code, or "—" when empty.
func optCode(s string) string {
	if s == "" {
		return none
	}
	return code(s)
}

// code renders s as inline code safe for a table cell, using a longer fence
// when s itself contains backticks.
func code(s string) string {
	s = strings.ReplaceAll(oneLine(s), "|", `\|`)
	if s == "" {
		return none
	}
	fence := "`"
	for strings.Contains(s, fence) {
		fence += "`"
	}
	if fence == "`" {
		return fence + s + fence
	}
	return fence + " " + s + " " + fence
}
