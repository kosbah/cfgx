func TestGen_NoModRoot(t *testing.T) {
	dir := t.TempDir()
	schema := filepath.Join(dir, "schema.go")
	copyFile(t, testSchema(t, "minimal.go"), schema)
	if _, errOut, code := runCLI(t, "gen", "-s", schema); code != 0 {
		// A go.mod above the temp dir would change the output root; that is
		// fine as long as gen succeeds.
		t.Fatalf("gen: code %d\n%s", code, errOut)
	}
	assertExists(t, filepath.Join(dir, "config.gen.go"))
}

func TestGen_Skips(t *testing.T) {
	dir := genProject(t)
	out, errOut, code := runCLI(t, "gen", "-s", filepath.Join(dir, "cmd", "schema.go"), "--no-env", "--no-docs")
	if code != 0 {
		t.Fatalf("gen: code %d\n%s", code, errOut)
	}
	assertExists(t, filepath.Join(dir, "cmd", "config.gen.go"),
		filepath.Join(dir, "config.example.yaml"), filepath.Join(dir, "config.schema.json"))
	assertMissing(t, filepath.Join(dir, ".env.example"), filepath.Join(dir, "docs"))
	if n := strings.Count(out, "✓ wrote"); n != 3 {
		t.Errorf("got %d wrote lines, want 3:\n%s", n, out)
	}

	dir = genProject(t)
	if _, errOut, code := runCLI(t, "gen", "-s", filepath.Join(dir, "cmd", "schema.go"), "--no-yaml", "--no-json-schema"); code != 0 {
		t.Fatalf("gen: code %d\n%s", code, errOut)
	}
	assertExists(t, filepath.Join(dir, ".env.example"), filepath.Join(dir, "docs", "config.md"))
	assertMissing(t, filepath.Join(dir, "config.example.yaml"), filepath.Join(dir, "config.schema.json"))
}

func TestGen_DryRun(t *testing.T) {
	dir := genProject(t)
	chdir(t, dir)
	out, errOut, code := runCLI(t, "gen", "--dry-run")
	if code != 0 {
		t.Fatalf("gen --dry-run: code %d\n%s", code, errOut)
	}
	if n := strings.Count(out, "would write "); n != 6 {
		t.Errorf("got %d would-write lines, want 6:\n%s", n, out)
	}
	assertContains(t, "dry-run output", out, "would write cmd/config.gen.go", "would write docs/config.1")
	assertMissing(t, filepath.Join(dir, "cmd", "config.gen.go"))
	for _, f := range artifactFiles {
		assertMissing(t, filepath.Join(dir, filepath.FromSlash(f)))
	}
}

func TestGen_AutoDiscover(t *testing.T) {
	t.Run("one", func(t *testing.T) {
		dir := genProject(t)
		// Files that must not be picked up.
		writeFile(t, filepath.Join(dir, "other", "schema.go"), "package other\n")
		copyFile(t, testSchema(t, "minimal.go"), filepath.Join(dir, "testdata", "schema.go"))
		copyFile(t, testSchema(t, "minimal.go"), filepath.Join(dir, ".hidden", "schema.go"))
		chdir(t, dir)
		if _, errOut, code := runCLI(t, "gen"); code != 0 {
			t.Fatalf("gen: code %d\n%s", code, errOut)
		}
		assertExists(t, filepath.Join(dir, "cmd", "config.gen.go"), filepath.Join(dir, ".env.example"))
	})
	t.Run("none", func(t *testing.T) {
		chdir(t, t.TempDir())
		_, errOut, code := runCLI(t, "gen")
		if code != 1 {
			t.Fatalf("code %d, want 1", code)
		}
		assertContains(t, "stderr", errOut, "no schema found", "--schema")
	})
	t.Run("many", func(t *testing.T) {
		dir := genProject(t)
		copyFile(t, testSchema(t, "minimal.go"), filepath.Join(dir, "tools", "schema.go"))
		chdir(t, dir)
		_, errOut, code := runCLI(t, "gen")
		if code != 1 {
			t.Fatalf("code %d, want 1", code)
		}
		assertContains(t, "stderr", errOut, "found 2 schema files", filepath.Join("cmd", "schema.go"), filepath.Join("tools", "schema.go"))
		assertMissing(t, filepath.Join(dir, "cmd", "config.gen.go"))
	})
}

func TestGen_ParseError(t *testing.T) {
	dir := t.TempDir()
	copyFile(t, testSchema(t, "invalid_duplicate.go"), filepath.Join(dir, "cmd", "schema.go"))
	chdir(t, dir)
	out, errOut, code := runCLI(t, "gen", "-s", "cmd/schema.go")
	if code != 1 {
		t.Fatalf("code %d, want 1", code)
	}
	want := "✗ parse error: " + filepath.Join("cmd", "schema.go") + `:8:2: duplicate entry ID "port"` + "\n"
	if errOut != want {
		t.Errorf("stderr = %q, want %q", errOut, want)
	}
	if out != "" {
		t.Errorf("stdout = %q, want empty", out)
	}
	assertMissing(t, filepath.Join(dir, "cmd", "config.gen.go"))
}

