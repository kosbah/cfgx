func TestGen_ProducesAllFiles(t *testing.T) {
	dir := genProject(t)
	chdir(t, dir)
	out, errOut, code := runCLI(t, "gen", "-s", "cmd/schema.go")
	if code != 0 {
		t.Fatalf("gen: code %d\nstdout:\n%s\nstderr:\n%s", code, out, errOut)
	}
	assertExists(t, filepath.Join(dir, "cmd", "config.gen.go"))
	for _, f := range artifactFiles {
		assertExists(t, filepath.Join(dir, filepath.FromSlash(f)))
	}

	gen := readFile(t, filepath.Join(dir, "cmd", "config.gen.go"))
	assertContains(t, "config.gen.go", gen,
		"// Code generated by cfgx. DO NOT EDIT.", "// Source: cmd/schema.go", "package testschema", "func LoadServe(")
	assertContains(t, "config.1", readFile(t, filepath.Join(dir, "docs", "config.1")), `.\" `+filepath.Base(dir)+" ")

	// Summary: one aligned line per file, paths relative to cwd, line counts.
	lines := strings.Split(strings.TrimSpace(out), "\n")
	if len(lines) != 6 {
		t.Fatalf("got %d summary lines, want 6:\n%s", len(lines), out)
	}
	want := append([]string{"cmd/config.gen.go"}, artifactFiles...)
	re := regexp.MustCompile(`^✓ wrote (\S+) +\((\d+) lines\)$`)
	for i, l := range lines {
		m := re.FindStringSubmatch(l)
		if m == nil || m[1] != filepath.FromSlash(want[i]) {
			t.Errorf("summary line %d = %q, want file %s", i, l, want[i])
			continue
		}
		content := readFile(t, filepath.Join(dir, filepath.FromSlash(want[i])))
		if n := strings.Count(content, "\n"); m[2] != strconv.Itoa(n) {
			t.Errorf("%s: reported %s lines, file has %d", want[i], m[2], n)
		}
	}
	if idx := strings.Index(lines[0], "("); idx != strings.Index(lines[1], "(") {
		t.Errorf("summary not aligned:\n%s", out)
	}
}

func TestGen_OutDir(t *testing.T) {
	dir := genProject(t)
	out := filepath.Join(t.TempDir(), "artifacts")
	stdout, errOut, code := runCLI(t, "gen", "--schema", filepath.Join(dir, "cmd", "schema.go"), "--out-dir", out)
	if code != 0 {
		t.Fatalf("gen: code %d\n%s%s", code, stdout, errOut)
	}
	assertExists(t, filepath.Join(dir, "cmd", "config.gen.go"))
	for _, f := range artifactFiles {
		assertExists(t, filepath.Join(out, filepath.FromSlash(f)))
		assertMissing(t, filepath.Join(dir, filepath.FromSlash(f)))
	}
}

